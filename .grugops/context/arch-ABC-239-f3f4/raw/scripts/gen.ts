// arch-ABC-239-f3f4: write a variant src/evaluate-params.ts from the base and candidate tables.
// usage: node gen.ts <tabsdir> <out.ts> <spec>; spec = base | cand | revert:F[,G] | import:F | revert-mg:F | revert-eg:F
import { writeFileSync } from "node:fs";
const [tabs, out, spec] = process.argv.slice(2) as [string, string, string];
const B = await import(`${tabs}/base.ts`);
const C = await import(`${tabs}/cand.ts`);
export const FAMILIES: Record<string, string[]> = {
  P: ["PST.pawn"], NB: ["PST.knight", "PST.bishop"], R: ["PST.rook"], Q: ["PST.queen"], K: ["PST.king"],
  PASS: ["PASSED"], STRUCT: ["DOUBLED", "ISOLATED"],
  KFILE: ["KING_SHELTER_MISSING", "KING_FILE_HALF_OPEN", "KING_FILE_OPEN", "KING_SHELTER_MISSING_QUEEN", "KING_FILE_HALF_OPEN_QUEEN", "KING_FILE_OPEN_QUEEN"],
  MOB: ["MOBILITY_WEIGHT"],
};
const clone = (m: Record<string, unknown>) => JSON.parse(JSON.stringify(Object.fromEntries(Object.entries(m))));
const [kind, fams = ""] = spec.split(":");
const from = kind === "import" ? B : C; // the table we start from
const other = kind === "import" ? C : B; // where the family's values come from
const t = clone(kind === "base" ? B : from);
const get = (m: any, path: string) => path.split(".").reduce((o, k) => o[k], m);
const halves = kind === "revert-mg" ? ["mg"] : kind === "revert-eg" ? ["eg"] : ["mg", "eg"];
if (kind !== "base" && kind !== "cand") {
  for (const f of fams.split(",")) {
    const paths = FAMILIES[f];
    if (!paths) throw new Error(`unknown family ${f}`);
    for (const p of paths) {
      const src = clone({ v: get(other, p) }).v;
      const dst = get(t, p);
      for (const h of halves) dst[h] = src[h];
    }
  }
}
let s = "// generated by arch-ABC-239-f3f4 gen.ts: " + spec + "\nexport interface MgEg<T> { readonly mg: T; readonly eg: T; }\n";
for (const [k, v] of Object.entries(t)) s += `export const ${k} = ${JSON.stringify(v)};\n`;
writeFileSync(out, s);
