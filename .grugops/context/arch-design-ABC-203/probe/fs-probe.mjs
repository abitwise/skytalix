import { mkdirSync, openSync, writeSync, closeSync, symlinkSync, writeFileSync, chmodSync, mkdtempSync, rmSync, lstatSync, readdirSync } from "node:fs";
import { join } from "node:path";
const base = process.argv[2];
const code = (f) => { try { f(); return "ok"; } catch (e) { return e.code ?? `nocode:${e.message}`; } };
const fresh = (n) => { const d = join(base, n); mkdirSync(d); process.chdir(d); return d; };
fresh("a"); writeFileSync("games", "x");
console.log("games is a regular file, mkdir recursive:", code(() => mkdirSync("games", { recursive: true })));
console.log("games is a regular file, open wx:", code(() => openSync("games/x.pgn", "wx")));
fresh("b"); mkdirSync("games"); chmodSync("games", 0o555);
console.log("games 0555, mkdir recursive:", code(() => mkdirSync("games", { recursive: true })));
console.log("games 0555, open wx:", code(() => openSync("games/x.pgn", "wx")));
chmodSync("games", 0o755);
fresh("c"); mkdirSync("games"); symlinkSync("/nonexistent-target-zz", "games/x.pgn");
console.log("last component dangling symlink, open wx:", code(() => openSync("games/x.pgn", "wx")));
fresh("d"); mkdirSync("elsewhere"); symlinkSync("elsewhere", "games");
console.log("games symlink to dir, mkdir recursive:", code(() => mkdirSync("games", { recursive: true })));
console.log("games symlink to dir, open wx:", code(() => { const fd = openSync("games/x.pgn", "wx"); closeSync(fd); }), "landed in elsewhere:", readdirSync("elsewhere"));
fresh("e"); symlinkSync("/nonexistent-dir-zz", "games");
console.log("games dangling symlink, mkdir recursive:", code(() => mkdirSync("games", { recursive: true })));
fresh("f");
console.log("absent games, mkdir recursive:", code(() => mkdirSync("games", { recursive: true })), lstatSync("games").isDirectory());
