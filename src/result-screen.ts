/**
 * `ABC-044` — the result screen: how the game ends on screen.
 *
 * `ABC-019`'s loop computes `{ result, reason, exitCode }` and stops. A player saw the final frame —
 * a board, a status panel showing the side to MOVE, and a history pane showing the last
 * `HISTORY_ROWS` rows of a possibly 120-ply game — and then the process ended. Nothing said *you
 * were checkmated* and nothing showed the game. This module is the rows that say both.
 *
 * IT IS NOT A FRAME, and that is a scope decision rather than a formatting one. It is written after
 * the final frame, through the same `FrameSink`, in ONE write. It has no constant height, it is not
 * bounded by `MESSAGE_ROWS`, it does not go through `assembleFrame`'s width padding, and it pads no
 * row to a column. `INPUT_ENDED_NOTICE` (`src/turn-loop.ts` `INPUT_ENDED_NOTICE`) is the merged
 * precedent for a non-frame write to the sink. It is therefore NOT on the frame path, by
 * `ADR-0029`'s membership rule: it is neither in the load closure of
 * `src/history-pane.nfr.test.ts`'s `COMPOSITION_ROOT` nor loaded by a frame call (of the production
 * modules, only `src/cli.ts` imports it).
 *
 * IT DERIVES NO GAME STATE. A pure function of `LoopOutcome` and `GameHistory`, returning rows.
 * `history.ts` is imported as a TYPE ONLY, so this module adds no runtime importer of it and
 * `ADR-0002` clause 4's single-supplier rule — held as an EQUALITY by
 * `src/history-pane.nfr.test.ts`'s licence guard — is untouched. `turn-loop.ts` is a type-only
 * import for the same reason: the loop is the licensed driver, and importing it at runtime would
 * drag `history.ts` into this closure through the back door.
 *
 * THE EIGHT REASONS ARE READ, NOT DECIDED. `TerminalReason` is
 * `EndReason | ClaimableDraw | "resignation" | "engine-failure" | "engine-threw"` — five automatic
 * chess conditions (`src/gameend.ts`), two claimed draws, resignation, and TWO FAULTS that are not
 * chess outcomes at all. `REASON_PHRASE` below is exhaustive over the eight game outcomes and the
 * type makes it so: a ninth `TerminalReason` fails to compile here rather than printing `undefined`.
 *
 * A CLAIMED DRAW AND AN AUTOMATIC ONE READ DIFFERENTLY, and that is the epic's own amendment rather
 * than a wording preference. FIDE distinguishes a draw a player CLAIMS (9.2 threefold, 9.3
 * fifty-move) from one that arrives with no claim (9.6.1 fivefold, 9.6.2 seventy-five-move), so a
 * screen that says `draw by repetition` for both under-reports what happened in the game. Each pair's
 * two lines differ by more than the rule's name and neither is a substring of the other.
 *
 * A FAULT IS NEVER A CHESS OUTCOME (`ABC-019` `A10`). `engine-failure` and `engine-threw` arrive
 * with `result: null`; their line names no rule from the eight and none of the words `win`, `wins`,
 * `draw`, `checkmate`, `stalemate`, and it says the game did not finish. The exit code is still the
 * loop's `0` — `LoopOutcome.exitCode` is typed `0` and only `0`, and what distinguishes a fault from
 * a real game is the message, not the code (`src/cli.ts`'s header, `ABC-043`'s ruling).
 *
 * END OF INPUT GETS NO SCREEN AT ALL: `{ result: null, reason: null }` produces ZERO rows, so the
 * caller writes zero bytes. The loop has already written `INPUT_ENDED_NOTICE` and a second line
 * would double-report a session in which no game finished.
 *
 * THE MOVE LIST IS THE WHOLE GAME, produced the way `renderHistory` produces its WINDOW: parse
 * `initialFen`, replay forward, `toSan(position, move)` before each `makeMove`. The move number and
 * the column are read from the replayed position — `fullmoveNumber` and `blackToMove` — and never
 * computed from the array index, which is `src/history-pane.ts`'s merged rule and is wrong for any
 * history anchored anywhere but a white-to-move start. That is also where the leading half-row comes
 * from: a black-to-move anchor's first ply opens its own row with an empty white cell, elided here
 * the way a chess move list elides it (`12... Nf6`) because this screen has no fixed columns to
 * leave blank. NO LEGAL MOVE LIST IS PASSED TO `toSan` — `src/san.ts:19-22` makes that parameter a
 * contract and this module holds no such list.
 *
 * THE REPLAY IS PRICED RATHER THAN ASSUMED: `O(plies)`, the same shape as `renderHistory`'s and
 * `keyHistory`'s (~46-50 µs at 120 plies, `src/history.ts:13-15`), run ONCE after the last ply. It
 * is on no per-ply budget and `NFR-002` is not triggered.
 *
 * NOTHING HERE IS SANITIZED, and the reason is a property rather than an oversight: every string on
 * this screen is generated by this product from merged values, and no player-typed byte reaches it.
 * If that ever changes the sanitizer is `src/frame.ts`'s and this module must route through it.
 */

import { makeMove } from "./apply.ts";
import { parseFen } from "./fen.ts";
import type { GameHistory } from "./history.ts";
import type { Move } from "./moves.ts";
import { toSan } from "./san.ts";
import type { LoopOutcome, TerminalReason } from "./turn-loop.ts";

/** The eight game outcomes the screen names. The two faults are not in here, by construction. */
type GameOutcomeReason = Exclude<TerminalReason, "engine-failure" | "engine-threw">;

/**
 * How each of the eight reads, as the tail of the headline.
 *
 * THE FOUR REPETITION/MOVE-COUNT RULES CARRY THEIR MODE AND THEIR FIDE ARTICLE. `claimed by the
 * player to move` versus `automatic` is the epic's amendment; the article is what lets a player
 * check the claim against the laws. Neither of a pair's phrases is a substring of the other.
 */
const REASON_PHRASE: Readonly<Record<GameOutcomeReason, string>> = {
  checkmate: "by checkmate",
  stalemate: "by stalemate",
  "insufficient-material": "by insufficient material",
  "fivefold-repetition": "by fivefold repetition, automatic under FIDE 9.6.1",
  "seventy-five-move": "by the seventy-five-move rule, automatic under FIDE 9.6.2",
  "threefold-repetition": "by threefold repetition, claimed by the player to move under FIDE 9.2",
  "fifty-move": "by the fifty-move rule, claimed by the player to move under FIDE 9.3",
  resignation: "by resignation",
};

/** Who won, or that nobody did. `gameStatus`'s own result, never re-derived from the position. */
const RESULT_PHRASE: Readonly<Record<NonNullable<LoopOutcome["result"]>, string>> = {
  "white-wins": "White wins",
  "black-wins": "Black wins",
  draw: "Draw",
};

/**
 * The two faults, spelled so that neither is a chess outcome: no rule from the eight, none of the
 * five chess words, and the sentence the criterion asks for in both.
 */
const FAULT_LINE: Readonly<Record<"engine-failure" | "engine-threw", string>> = {
  "engine-failure": "The game did not finish: the engine returned a move that was not its to play.",
  "engine-threw": "The game did not finish: the engine threw an error.",
};

/** What a fault's line is followed by, so a player is not left thinking the program judged them. */
const FAULT_NOTE = "That is a bug in this program, not a chess outcome.";

/** One rendered pair. Either cell may stay empty: both half-rows are real (`history-pane.ts`). */
interface MovePair {
  readonly number: number;
  white: string;
  black: string;
}

/**
 * `12. e4 e5`, `12. e4` for a game White ended, `12... Nf6` for a black-to-move anchor's first pair.
 * The screen has no fixed columns, so a missing cell is elided rather than padded.
 */
const rowFor = (pair: MovePair): string =>
  pair.white === ""
    ? `${pair.number}... ${pair.black}`
    : `${pair.number}. ${pair.white}${pair.black === "" ? "" : ` ${pair.black}`}`;

/** Every ply of the game, in SAN, in move-number pairs. `renderHistory`'s replay, unwindowed. */
function moveList(history: GameHistory): readonly string[] {
  // The one `parseFen`: the anchor, parsed once, into this function's own object. The caller's
  // `history.position` is BORROWED (`history.ts:39-44`) and is never touched.
  const position = parseFen(history.initialFen);
  const pairs: MovePair[] = [];

  for (const move of history.moves) {
    const black = position.blackToMove;
    const number = position.fullmoveNumber;
    const san = toSan(position, move as Move);
    makeMove(position, move as Move);

    const open = pairs[pairs.length - 1];
    if (black && open !== undefined) open.black = san;
    else pairs.push({ number, white: black ? "" : san, black: black ? san : "" });
  }

  return pairs.map(rowFor);
}

/** The one line that says what happened — a chess outcome, or a fault that is not one. */
function headline(outcome: LoopOutcome, reason: TerminalReason): readonly string[] {
  if (reason === "engine-failure" || reason === "engine-threw")
    return [FAULT_LINE[reason], FAULT_NOTE];

  // `result` is non-null for all eight game outcomes: `ABC-019` returns `gameStatus`'s own result
  // alongside them, and `null` reaches here only on the two faults above.
  const result = RESULT_PHRASE[outcome.result as NonNullable<LoopOutcome["result"]>];
  return [`${result} ${REASON_PHRASE[reason as GameOutcomeReason]}.`];
}

/**
 * The result screen, as rows. Written after the final frame, in one write, by the entry point.
 *
 * ZERO ROWS on end of input, which is the whole of `reason === null`: the loop stopped without a
 * game to report and has already said so itself.
 */
export function renderResultScreen(outcome: LoopOutcome, history: GameHistory): readonly string[] {
  if (outcome.reason === null) return [];

  // The leading blank separates the screen from the final frame's last row — this is a write onto
  // the same stream, not a frame, and there is no writer between them to space it.
  return ["", ...headline(outcome, outcome.reason), "", ...moveList(history)];
}
